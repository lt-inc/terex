export function clipState(state?: string): {
  label: string;
  explanation: string;
} {
  const item = states[state || ""];
  return item
    ? { label: item[0], explanation: item[1] }
    : {
        label: state || "Неизвестно",
        explanation: "Обновите страницу, чтобы получить состояние обработки.",
      };
}

export function queueAgeLabel(oldestAt?: string): string {
  if (!oldestAt || oldestAt.startsWith("0001-")) return "очередь пуста / нет данных";
  const created = Date.parse(oldestAt);
  if (!Number.isFinite(created)) return "нет данных";
  const minutes = Math.max(0, Math.floor((Date.now() - created) / 60000));
  return minutes < 1 ? "меньше минуты" : minutes < 60 ? `${minutes} мин` : `${Math.floor(minutes / 60)} ч ${minutes % 60} мин`;
}
